"""Functions for converting expressions between CasADi and SymPy."""
import casadi as ca
import sympy as sp


OP_MAP = {
    ca.OP_ADD:      lambda a, b: a + b,
    ca.OP_SUB:      lambda a, b: a - b,
    ca.OP_MUL:      lambda a, b: a * b,
    ca.OP_DIV:      lambda a, b: a / b,
    ca.OP_POW:      lambda a, b: a ** b,
    ca.OP_CONSTPOW: lambda a, b: a ** b,
    ca.OP_NEG:      lambda a: -a,
    ca.OP_INV:      lambda a: 1 / a,
    ca.OP_SQ:       lambda a: a ** 2,
    ca.OP_TWICE:    lambda a: 2 * a,
    ca.OP_SQRT:     lambda a: sp.sqrt(a),
    ca.OP_FABS:     lambda a: sp.Abs(a),
    ca.OP_SIGN:     lambda a: sp.sign(a),
    ca.OP_EXP:      lambda a: sp.exp(a),
    ca.OP_LOG:      lambda a: sp.log(a),
    ca.OP_LOG1P:    lambda a: sp.log(1 + a),
    ca.OP_EXPM1:    lambda a: sp.exp(a) - 1,
    ca.OP_SIN:      lambda a: sp.sin(a),
    ca.OP_COS:      lambda a: sp.cos(a),
    ca.OP_TAN:      lambda a: sp.tan(a),
    ca.OP_ASIN:     lambda a: sp.asin(a),
    ca.OP_ACOS:     lambda a: sp.acos(a),
    ca.OP_ATAN:     lambda a: sp.atan(a),
    ca.OP_ATAN2:    lambda a, b: sp.atan2(a, b),
    ca.OP_SINH:     lambda a: sp.sinh(a),
    ca.OP_COSH:     lambda a: sp.cosh(a),
    ca.OP_TANH:     lambda a: sp.tanh(a),
    ca.OP_ASINH:    lambda a: sp.asinh(a),
    ca.OP_ACOSH:    lambda a: sp.acosh(a),
    ca.OP_ATANH:    lambda a: sp.atanh(a),
    ca.OP_ERF:      lambda a: sp.erf(a),
    ca.OP_ERFINV:   lambda a: sp.erfinv(a),
    ca.OP_FLOOR:    lambda a: sp.floor(a),
    ca.OP_CEIL:     lambda a: sp.ceiling(a),
    ca.OP_FMOD:     lambda a, b: sp.Mod(a, b),
    ca.OP_FMIN:     lambda a, b: sp.Min(a, b),
    ca.OP_FMAX:     lambda a, b: sp.Max(a, b),
    ca.OP_HYPOT:    lambda a, b: sp.sqrt(a**2 + b**2),
}


def casadi2sympy(expr, sym_map=None):
    """
    (Function generated by some AI, probably Gemini)
    Recursively convert a scalar CasADi SX expression to SymPy.
    sym_map: dict mapping CasADi symbol name → SymPy symbol (shared across calls)
    """
    if sym_map is None:
        sym_map = {}

    # Symbolic leaf
    if expr.is_symbolic():
        name = expr.name()
        if name not in sym_map:
            sym_map[name] = sp.Symbol(name)
        return sym_map[name], sym_map

    # Numeric constant
    if expr.is_constant():
        return sp.Rational(expr.__float__()).limit_denominator(10**9), sym_map

    op = expr.op()
    deps = [casadi2sympy(expr.dep(i), sym_map) for i in range(expr.n_dep())]
    # deps is list of (sympy_expr, sym_map) tuples
    sp_deps = [d[0] for d in deps]
    sym_map = deps[-1][1]  # all share the same sym_map

    if op not in OP_MAP:
        raise NotImplementedError(f"Unsupported CasADi op: {op} ({ca.OP_MAP.get(op, '?')})")

    return OP_MAP[op](*sp_deps), sym_map


def sympy2casadi(sympy_expr: sp.Function, sympy_var: sp.Matrix, casadi_var: ca.SX):
    """https://gist.github.com/jgillis/80bb594a6c8fcf55891d1d88b12b68b8"""
    assert casadi_var.is_vector(), "CasADi variables should be a vector"
    if casadi_var.shape[1]>1:
        casadi_var = casadi_var.T
    casadi_var = ca.vertsplit(casadi_var)

    mapping = {'ImmutableDenseMatrix': ca.blockcat, 'MutableDenseMatrix': ca.blockcat}
    f = sp.utilities.lambdify(sympy_var, sympy_expr, modules=[mapping, ca])
    return f(*casadi_var)
